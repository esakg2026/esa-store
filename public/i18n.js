function t(s) {
  if (LANG === "ru") return s;
  const d = DICT[LANG];
  if (d[s] != null) return d[s];
  const m = /^(\s*)(.*?)(\s*)$/.exec(s); // текст с пробелами по краям
  return m && d[m[2]] != null ? m[1] + d[m[2]] + m[3] : s;
}

